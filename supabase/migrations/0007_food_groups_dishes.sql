-- Food groups (MEXT 8th edition 01–18), countable units, and a library of common dishes.

alter table public.foods
  add column food_group smallint check (food_group between 1 and 18),
  add column unit_name text,
  add column unit_grams numeric(6, 1) check (unit_grams > 0),
  add constraint foods_unit_pair check ((unit_name is null) = (unit_grams is null));

create index foods_food_group_idx on public.foods (food_group);
create index foods_source_idx on public.foods (source);

