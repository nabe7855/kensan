/** Everyday words to make an official food name searchable (null when nothing applies). */
export function aliasesFor(name: string): string | null {
  const words = new Set<string>();
  for (const [keys, alias] of RULES) {
    if (keys.every((k) => name.includes(k))) alias.split(" ").forEach((w) => words.add(w));
  }
  return words.size > 0 ? [...words].join(" ") : null;
}
