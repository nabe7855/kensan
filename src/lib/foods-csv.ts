export type ParsedFood = {
  name: string;
  kcal: number;
  protein_g: number;
  fat_g: number;
  carb_g: number;
  fiber_g: number | null;
  sodium_mg: number | null;
};

/** Minimal RFC 4180 CSV parser (quoted fields, escaped quotes, CRLF). */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]!;
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += ch;
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((c) => c.trim() !== ""));
}

/** MEXT notation: "Tr" (trace) → 0, "(1.2)" (estimated) → 1.2, "-" / "" / "*" → null. */
export function parseMextNumber(raw: string | undefined): number | null {
  const s = (raw ?? "").trim().replace(/[()（）]/g, "");
  if (s === "" || s === "-" || s === "*" || s === "†") return null;
  if (/^tr$/i.test(s)) return 0;
  const n = Number(s.replace(/,/g, ""));
  return Number.isFinite(n) ? n : null;
}

const norm = (s: string) => s.replace(/\s|　/g, "").toLowerCase();

/** Column index: exact header match first, then the first header containing the text. */
function findColumn(
  headers: string[],
  exact: string[],
  contains: string[],
  exclude: string[] = [],
) {
  const h = headers.map(norm);
  for (const e of exact) {
    const i = h.indexOf(norm(e));
    if (i >= 0) return i;
  }
  return h.findIndex(
    (x) => contains.some((c) => x.includes(norm(c))) && !exclude.some((e) => x.includes(norm(e))),
  );
}

/**
 * Parse a CSV exported from the MEXT 8th edition table. The header row is the first row
 * that contains a "食品名" column; multi-row headers above it are ignored.
 */
export function parseMextFoods(text: string): { foods: ParsedFood[]; skipped: number } {
  const rows = parseCsv(text);
  const headerIdx = rows.findIndex((r) => r.some((c) => norm(c).includes("食品名")));
  if (headerIdx < 0) throw new Error("食品名 の列が見つかりません");
  const headers = rows[headerIdx]!;
  const col = {
    name: findColumn(headers, ["食品名"], ["食品名"]),
    kcal: findColumn(headers, ["エネルギー(kcal)", "エネルギー（kcal）"], ["kcal"]),
    protein: findColumn(headers, ["たんぱく質"], ["たんぱく質"], ["アミノ酸"]),
    fat: findColumn(headers, ["脂質"], ["脂質"], ["トリアシル", "脂肪酸"]),
    carb: findColumn(headers, ["炭水化物"], ["炭水化物"], ["利用可能", "差引"]),
    fiber: findColumn(headers, ["食物繊維総量"], ["食物繊維総量"]),
    sodium: findColumn(headers, ["ナトリウム"], ["ナトリウム"]),
  };
  for (const [key, i] of Object.entries(col)) {
    if (i < 0 && key !== "fiber" && key !== "sodium")
      throw new Error(`${key} の列が見つかりません`);
  }

  const foods: ParsedFood[] = [];
  let skipped = 0;
  for (const r of rows.slice(headerIdx + 1)) {
    const name = (r[col.name] ?? "").trim();
    const kcal = parseMextNumber(r[col.kcal]);
    if (!name || kcal === null) {
      skipped++;
      continue;
    }
    foods.push({
      name,
      kcal,
      protein_g: parseMextNumber(r[col.protein]) ?? 0,
      fat_g: parseMextNumber(r[col.fat]) ?? 0,
      carb_g: parseMextNumber(r[col.carb]) ?? 0,
      fiber_g: col.fiber >= 0 ? parseMextNumber(r[col.fiber]) : null,
      sodium_mg: col.sodium >= 0 ? parseMextNumber(r[col.sodium]) : null,
    });
  }
  return { foods, skipped };
}

const sqlText = (s: string) => `'${s.replace(/'/g, "''")}'`;
const sqlNum = (n: number | null) => (n === null ? "null" : String(n));

/** Migration SQL inserting the foods as system rows (source 'mext8'). */
export function foodsToSql(foods: ParsedFood[]): string {
  const values = foods
    .map(
      (f) =>
        `  (${sqlText(f.name)}, ${sqlNum(f.kcal)}, ${sqlNum(f.protein_g)}, ${sqlNum(f.fat_g)}, ${sqlNum(f.carb_g)}, ${sqlNum(f.fiber_g)}, ${sqlNum(f.sodium_mg)}, ${/ゆで|めし|焼き|蒸し|揚げ|炒め|煮/.test(f.name)})`,
    )
    .join(",\n");
  return `-- Generated by scripts/import-foods.mts from the MEXT 8th edition CSV.

delete from public.foods f
where f.source = 'mext8' and f.user_id is null
  and not exists (select 1 from public.meal_log_items i where i.food_id = f.id)
  and not exists (select 1 from public.meal_template_items t where t.food_id = f.id);

insert into public.foods (user_id, source, name, kcal, protein_g, fat_g, carb_g, fiber_g, sodium_mg, is_cooked)
select null, 'mext8', v.name, v.kcal, v.p, v.f, v.c, v.fiber, v.na, v.cooked
from (values
${values}
) as v(name, kcal, p, f, c, fiber, na, cooked)
where not exists (
  select 1 from public.foods x where x.source = 'mext8' and x.user_id is null and x.name = v.name
);
`;
}
